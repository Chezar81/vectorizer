#!/usr/bin/env bash
# User-local install (no sudo): venv, PATH launcher, icons, menu starter.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENV="${ROOT}/.venv"
BIN="${HOME}/.local/bin"
APPS="${HOME}/.local/share/applications"
ICONS="${HOME}/.local/share/icons/hicolor"

# Localized Desktop folder (Mint DE often uses ~/Schreibtisch).
DESKTOP_DIR=""
if [[ -f "${HOME}/.config/user-dirs.dirs" ]]; then
  # shellcheck disable=SC1091
  source "${HOME}/.config/user-dirs.dirs"
  if [[ -n "${XDG_DESKTOP_DIR:-}" ]]; then
    DESKTOP_DIR="${XDG_DESKTOP_DIR/#\$HOME/${HOME}}"
  fi
fi
if [[ -z "${DESKTOP_DIR}" || ! -d "${DESKTOP_DIR}" ]]; then
  for candidate in "${HOME}/Desktop" "${HOME}/Schreibtisch"; do
    if [[ -d "${candidate}" ]]; then
      DESKTOP_DIR="${candidate}"
      break
    fi
  done
fi

mkdir -p "${BIN}" "${APPS}" "${ICONS}"

if [[ ! -x "${VENV}/bin/python" ]]; then
  python3 -m venv "${VENV}"
fi

"${VENV}/bin/python" -m pip install --upgrade pip
"${VENV}/bin/python" -m pip install -e "${ROOT}[dev]"

LIBDIR="${ROOT}/.local-libs/extracted/usr/lib/x86_64-linux-gnu"
WRAPPER="${BIN}/vectorizer"
cat > "${WRAPPER}" <<EOF
#!/usr/bin/env bash
# Vectorizer user launcher (generated by scripts/install-user.sh)
set -euo pipefail
ROOT="${ROOT}"
VENV="${VENV}"
LIBDIR="${LIBDIR}"
if [[ -d "\${LIBDIR}" ]]; then
  export LD_LIBRARY_PATH="\${LIBDIR}\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}"
fi
export DISPLAY="\${DISPLAY:-:0}"
exec "\${VENV}/bin/vectorizer" "\$@"
EOF
chmod +x "${WRAPPER}"

# Install theme icons (PNG sizes + scalable SVG).
if [[ -d "${ROOT}/packaging/icons/hicolor" ]]; then
  cp -a "${ROOT}/packaging/icons/hicolor/." "${ICONS}/"
fi

DESKTOP_SRC="${ROOT}/packaging/vectorizer.desktop"
DESKTOP_DST="${APPS}/vectorizer.desktop"
# Absolute Exec so the menu works even when ~/.local/bin is not on PATH.
sed \
  -e "s|^Exec=vectorizer|Exec=${WRAPPER}|" \
  -e "s|^TryExec=vectorizer|TryExec=${WRAPPER}|" \
  "${DESKTOP_SRC}" > "${DESKTOP_DST}"
chmod +x "${DESKTOP_DST}"

# Optional desktop shortcut (Cinnamon / Mint home Desktop).
if [[ -d "${DESKTOP_DIR}" ]]; then
  cp "${DESKTOP_DST}" "${DESKTOP_DIR}/vectorizer.desktop"
  chmod +x "${DESKTOP_DIR}/vectorizer.desktop"
  # Mark trusted on glib-based desktops when possible.
  if command -v gio >/dev/null 2>&1; then
    gio set "${DESKTOP_DIR}/vectorizer.desktop" metadata::trusted true 2>/dev/null || true
  fi
  echo "Desktop shortcut: ${DESKTOP_DIR}/vectorizer.desktop"
fi

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "${APPS}" || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
  gtk-update-icon-cache -f -t "${ICONS}" 2>/dev/null || true
fi

echo "Installed user launcher: ${WRAPPER}"
echo "Menu entry: ${DESKTOP_DST}"
echo "Icon theme: ${ICONS}/*/apps/vectorizer.png (+ scalable SVG)"
echo "Open from the app menu as “Vectorizer”, or run: vectorizer"
echo "(Ensure ${BIN} is on PATH for the shell command.)"
